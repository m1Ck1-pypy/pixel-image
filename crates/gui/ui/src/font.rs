//! 5x7 bitmap font taken from the reference project.
//!
//! The table is uppercase-only; lowercase characters are folded to uppercase
//! before lookup. It covers Latin, Cyrillic, digits, basic punctuation and the
//! arrows used by the interface.

use std::collections::HashMap;

use crate::canvas::Canvas;
use crate::color::Color;

const GLYPH_W: i32 = 5;
const GLYPH_H: i32 = 7;
const ADVANCE: i32 = 6;

pub struct Font {
    glyphs: HashMap<char, [u8; GLYPH_H as usize]>,
}

impl Font {
    pub fn new() -> Self {
        let mut glyphs = HashMap::new();
        for (ch, rows) in GLYPHS {
            let mut bitmap = [0u8; GLYPH_H as usize];
            for (y, row) in rows.iter().enumerate().take(GLYPH_H as usize) {
                let mut bits = 0u8;
                for (x, cell) in row.chars().take(GLYPH_W as usize).enumerate() {
                    if cell == '#' {
                        bits |= 1 << (GLYPH_W as usize - 1 - x);
                    }
                }
                bitmap[y] = bits;
            }
            glyphs.insert(*ch, bitmap);
        }
        Self { glyphs }
    }

    /// Pixel height of one glyph at `scale`, in logical pixels.
    pub fn glyph_height(scale: i32) -> i32 {
        GLYPH_H * scale.max(1)
    }

    /// Distance between two baselines, in logical pixels.
    pub fn line_height(scale: i32) -> i32 {
        (GLYPH_H + 2) * scale.max(1)
    }

    /// Horizontal advance of one character, in logical pixels.
    pub fn advance(&self, scale: i32) -> i32 {
        ADVANCE * scale.max(1)
    }

    pub fn width(&self, text: &str, scale: i32) -> i32 {
        let scale = scale.max(1);
        let mut widest = 0;
        let mut line_advance = 0;
        let mut line_has_chars = false;
        for ch in text.chars() {
            if ch == '\n' {
                widest = widest.max(line_width(line_advance, line_has_chars, scale));
                line_advance = 0;
                line_has_chars = false;
            } else {
                line_advance += ADVANCE * scale;
                line_has_chars = true;
            }
        }
        widest.max(line_width(line_advance, line_has_chars, scale))
    }

    pub fn draw(&self, canvas: &mut Canvas, x: i32, y: i32, text: &str, color: Color, scale: i32) {
        self.draw_inner(canvas, x, y, text, color, scale.max(1));
    }

    pub fn draw_centered(
        &self,
        canvas: &mut Canvas,
        center_x: i32,
        y: i32,
        text: &str,
        color: Color,
        scale: i32,
    ) {
        let width = self.width(text, scale);
        self.draw(canvas, center_x - width / 2, y, text, color, scale);
    }

    pub fn draw_right(
        &self,
        canvas: &mut Canvas,
        right: i32,
        y: i32,
        text: &str,
        color: Color,
        scale: i32,
    ) {
        let width = self.width(text, scale);
        self.draw(canvas, right - width, y, text, color, scale);
    }

    fn draw_inner(
        &self,
        canvas: &mut Canvas,
        x: i32,
        y: i32,
        text: &str,
        color: Color,
        scale: i32,
    ) {
        let mut cx = x;
        let mut cy = y;
        for ch in text.chars() {
            match ch {
                '\n' => {
                    cx = x;
                    cy += (GLYPH_H + 2) * scale;
                }
                ' ' => cx += ADVANCE * scale,
                _ => {
                    self.draw_char(canvas, cx, cy, ch, color, scale);
                    cx += ADVANCE * scale;
                }
            }
        }
    }

    fn draw_char(&self, canvas: &mut Canvas, x: i32, y: i32, ch: char, color: Color, scale: i32) {
        let upper = ch.to_uppercase().next().unwrap_or(ch);
        let bitmap = self
            .glyphs
            .get(&upper)
            .or_else(|| self.glyphs.get(&'?'))
            .copied()
            .unwrap_or([0; GLYPH_H as usize]);
        for (row, bits) in bitmap.iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (1 << (GLYPH_W - 1 - col)) != 0 {
                    canvas.fill_rect(x + col * scale, y + row as i32 * scale, scale, scale, color);
                }
            }
        }
    }
}

impl Default for Font {
    fn default() -> Self {
        Self::new()
    }
}

fn line_width(advance: i32, has_chars: bool, scale: i32) -> i32 {
    if has_chars { advance - scale } else { 0 }
}

